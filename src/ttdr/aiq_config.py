"""Render AI-Q's config from the recipe, so swapping the LLM is a recipe change only.

configs/aiq/ttdr.yml holds AI-Q's structure and each role's intent (thinking on or off, token
limits). Rendering fills in the recipe's LLM (name, URL, sampling) and translates the thinking
intent into that model's reasoning control.
"""

from pathlib import Path

import yaml

from ttdr.recipe import Model, Recipe

BASE = Path("configs/aiq/ttdr.yml")
OUT = Path("data/aiq/config/ttdr.yml")


def _llm(entry: dict, m: Model) -> dict:
    body = entry.get("extra_body") or {}
    thinking = bool(body.get("chat_template_kwargs", {}).get("enable_thinking"))
    return {**entry, "model_name": m.model, "base_url": m.url, **m.request_settings(thinking)}


def render(recipe: Recipe, base: Path = BASE) -> dict:
    cfg = yaml.safe_load(base.read_text())
    cfg["llms"] = {name: _llm(e, recipe.llm) for name, e in cfg["llms"].items()}
    for group, path in (("web", "web"), ("documents", "docs")):
        cfg["function_groups"][group]["server"]["url"] = f"{recipe.services.mcp}/{path}"
    for source in cfg["functions"]["data_sources"]["sources"]:
        if source["id"] == "documents" and recipe.corpora:
            source["description"] += "\nPrivate collections:\n" + recipe.corpus_catalog()
    return cfg


def write(recipe: Recipe, out: Path = OUT) -> Path:
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "# Generated by `ttdr aiq-config` from recipe.toml + configs/aiq/ttdr.yml. Don't edit.\n"
        + yaml.safe_dump(render(recipe), sort_keys=False)
    )
    return out
